// ✅ NEW FILE — Export Excel for the Enquiry module (additive only).
// Pulls EVERY enquiry via the existing GET /enquiry endpoint (no filters, paged),
// flattens each one with the SAME row logic as EnquiryTable.js, and downloads
// Blue_Ocean_Enquiry_Export.xlsx. No existing file/API/schema is modified.

// ─── Date helpers (identical output to EnquiryTable.js) ──────────────────────
const MONTHS = ["Jan","Feb","Mar","Apr","May","Jun","Jul","Aug","Sep","Oct","Nov","Dec"];
function formatDate(dateStr) {
  if (!dateStr) return "—";
  const d = new Date(dateStr);
  if (isNaN(d)) return "—";
  return `${String(d.getDate()).padStart(2, "0")}-${MONTHS[d.getMonth()]}-${String(d.getFullYear()).slice(-2)}`;
}
function formatDateISO(dateStr) {
  if (!dateStr) return "—";
  const d = new Date(dateStr);
  if (isNaN(d)) return "—";
  return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, "0")}-${String(d.getDate()).padStart(2, "0")}`;
}

// ─── Part rows (mirror of buildRows in EnquiryTable.js) ──────────────────────
function buildPartRows(enq) {
  const partSuppliersMap = {};
  (Array.isArray(enq.partSuppliers) ? enq.partSuppliers : []).forEach((ps) => {
    const list = Array.isArray(ps.suppliers) ? ps.suppliers : [];
    partSuppliersMap[ps.customerPartNo] = list.map((s) =>
      typeof s === "string"
        ? { name: s, poNumber: "", dateOfIssue: "" }
        : { name: s.name || "", poNumber: s.poNumber || "", dateOfIssue: s.dateOfIssue || "" }
    );
  });
  const resolveSuppliers = (partNo) => partSuppliersMap[partNo] || [];

  const parts =
    Array.isArray(enq.parts) && enq.parts.length > 0
      ? enq.parts
      : enq.partMapping?.customerPartNo
      ? [{ customerPartNo: enq.partMapping.customerPartNo, modifiedBOPartNo: enq.partMapping.modifiedBOPartNo, boPartName: enq.partMapping.boPartName, children: [] }]
      : [{ customerPartNo: "—", modifiedBOPartNo: "", boPartName: "", children: [] }];

  const rows = [];
  parts.forEach((parent) => {
    rows.push({
      partNo: parent.customerPartNo || "—",
      boPartName: parent.boPartName || "",
      boPartNo: parent.modifiedBOPartNo || "",
      itemDescription: parent.itemDescription || "",
      suppliers: resolveSuppliers(parent.customerPartNo),
    });
    (Array.isArray(parent.children) ? parent.children : []).forEach((child) => {
      rows.push({
        partNo: child.customerPartNo || "—",
        boPartName: child.boPartName || "",
        boPartNo: child.modifiedBOPartNo || "",
        itemDescription: child.itemDescription || "",
        suppliers: resolveSuppliers(child.customerPartNo),
      });
    });
  });
  return rows;
}

// ─── One enquiry → flat Excel rows (12 columns, UI order) ────────────────────
// A part with N suppliers becomes N rows, so no supplier / PO / date is lost.
// Inquiry No, Customer Name, RFQ Date and Generated By/On repeat on every row.
export function buildExportRows(enq) {
  const out = [];
  const partRows = buildPartRows(enq);
  const hasPartSuppliers = partRows.some((r) => r.suppliers.length > 0);

  partRows.forEach((pr) => {
    const desc = pr.itemDescription || enq.itemDescription || "";
    const poLines = hasPartSuppliers
      ? pr.suppliers.map((s) => [s.name || "—", s.poNumber || "—", s.dateOfIssue ? formatDate(s.dateOfIssue) : "—"])
      : [[enq.poDetails?.supplierName || "—", enq.poDetails?.poNumber || "—", formatDate(enq.poDetails?.dateOfIssue)]];
    if (poLines.length === 0) poLines.push(["—", "—", "—"]); // part with no supplier

    poLines.forEach((po) => {
      out.push([
        enq.enquiryNumber || "—",
        enq.customerName || "—",
        formatDateISO(enq.customerRFQDate),
        desc || "—",
        pr.partNo,
        pr.boPartName || "—",
        pr.boPartNo || "—",
        ...po,
        enq.generatedBy || "—",
        formatDate(enq.createdAt),
      ]);
    });
  });
  return out;
}

const GROUPS = [
  { title: "BO / ENQUIRY DETAILS", cols: ["Inquiry No", "Customer Name", "RFQ Date", "Item Description"], bg: "FFBFDBFE", fg: "FF1E3A8A" },
  { title: "PART NUMBER MAPPING", cols: ["Customer Part No", "BO Part Name", "BO Part No"], bg: "FFDDD6FE", fg: "FF5B21B6" },
  { title: "PO / SUPPLIER", cols: ["Supplier", "PO Number", "Date of Issue"], bg: "FFBBF7D0", fg: "FF166534" },
  { title: "GENERATED", cols: ["Generated By", "Generated On"], bg: "FFFED7AA", fg: "FF9A3412" },
];
const THIN = { style: "thin", color: { argb: "FF94A3B8" } };
const BORDER = { top: THIN, left: THIN, bottom: THIN, right: THIN };

// ─── Build workbook (exceljs gives real cell styling; SheetJS CE does not) ───
export async function buildWorkbook(enquiries) {
 // ✅ NEW — use the prebuilt browser bundle
const ExcelJS = (await import("exceljs/dist/exceljs.min.js")).default;
  const wb = new ExcelJS.Workbook();
  const ws = wb.addWorksheet("Enquiries", { views: [{ state: "frozen", ySplit: 2 }] });

  const totalCols = GROUPS.reduce((n, g) => n + g.cols.length, 0);

  // Row 1 — grouped headings (merged), Row 2 — column headings
  let c = 1;
  GROUPS.forEach((g) => {
    const start = c;
    const end = c + g.cols.length - 1;
    ws.mergeCells(1, start, 1, end);
    const top = ws.getCell(1, start);
    top.value = g.title;
    for (let i = start; i <= end; i++) {
      const gc = ws.getCell(1, i);
      gc.font = { bold: true, size: 12, color: { argb: g.fg } };
      gc.fill = { type: "pattern", pattern: "solid", fgColor: { argb: g.bg } };
      gc.alignment = { horizontal: "center", vertical: "middle" };
      gc.border = BORDER;
    }
    g.cols.forEach((name, i) => {
      const hc = ws.getCell(2, start + i);
      hc.value = name;
      hc.font = { bold: true, size: 11, color: { argb: "FFFFFFFF" } };
      hc.fill = { type: "pattern", pattern: "solid", fgColor: { argb: "FF334155" } };
      hc.alignment = { horizontal: "center", vertical: "middle", wrapText: true };
      hc.border = BORDER;
    });
    c = end + 1;
  });
  ws.getRow(1).height = 24;
  ws.getRow(2).height = 22;

  // Data rows
  const widths = GROUPS.flatMap((g) => g.cols).map((h) => h.length + 4);
  enquiries.forEach((enq) => {
    buildExportRows(enq).forEach((vals) => {
      const row = ws.addRow(vals);
      row.eachCell({ includeEmpty: true }, (cell, col) => {
        cell.border = BORDER;
        cell.alignment = { vertical: "top", wrapText: col === 4, horizontal: col === 3 || col === 10 || col === 12 ? "center" : "left" };
      });
      vals.forEach((v, i) => { widths[i] = Math.max(widths[i], String(v).length + 2); });
    });
  });
  widths.forEach((w, i) => { ws.getColumn(i + 1).width = Math.min(Math.max(w, 12), i === 3 ? 50 : 40); });

  ws.autoFilter = { from: { row: 2, column: 1 }, to: { row: 2, column: totalCols } };
  return wb;
}

// ─── Fetch ALL enquiries (ignores UI filters / pagination) ───────────────────
export async function fetchAllEnquiries(API) {
  const PAGE_SIZE = 500;
  const all = [];
  let page = 1;
  let totalPages = 1;
  do {
    const res = await API.get("/enquiry", { params: { page, limit: PAGE_SIZE } });
    all.push(...(res.data.enquiries || []));
    totalPages = res.data.totalPages || 1;
    page += 1;
  } while (page <= totalPages);
  return all;
}

export async function exportEnquiriesToExcel(API) {
  const enquiries = await fetchAllEnquiries(API);
  const wb = await buildWorkbook(enquiries);
  const buffer = await wb.xlsx.writeBuffer();
  const blob = new Blob([buffer], { type: "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = "Blue_Ocean_Enquiry_Export.xlsx";
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
  return enquiries.length;
}
